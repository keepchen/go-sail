package utils

import (
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

var anotherArgon2Config = Argon2Config{
	Memory:      32 * 1024, //32MB
	Iterations:  6,
	Parallelism: 8,
	SaltLength:  16,
	KeyLength:   32,
}

func TestArgon2(t *testing.T) {
	t.Run("Argon2", func(t *testing.T) {
		assert.NotNil(t, Argon2())
	})
	t.Run("Argon2-With-Config", func(t *testing.T) {
		assert.NotNil(t, Argon2(anotherArgon2Config))
	})
}

func TestArgon2HashMake(t *testing.T) {
	t.Run("Argon2HashMake", func(t *testing.T) {
		result, err := Argon2().HashMake("password")
		assert.Nil(t, err)
		assert.NotEmpty(t, result)
	})
	t.Run("Argon2HashMake-Another-Config", func(t *testing.T) {
		result, err := Argon2(anotherArgon2Config).HashMake("password")
		assert.Nil(t, err)
		assert.NotEmpty(t, result)
	})
}

func TestArgon2HashCheck(t *testing.T) {
	t.Run("Argon2HashCheck", func(t *testing.T) {
		hashed, err := Argon2().HashMake("password")
		assert.Nil(t, err)
		assert.NotEmpty(t, hashed)
		valid, err := Argon2().HashCheck("password", hashed)
		assert.Nil(t, err)
		assert.True(t, valid)
	})
	t.Run("Argon2HashCheck-Another-Config", func(t *testing.T) {
		hashed, err := Argon2(anotherArgon2Config).HashMake("password")
		assert.Nil(t, err)
		assert.NotEmpty(t, hashed)
		valid, err := Argon2().HashCheck("password", hashed)
		assert.Nil(t, err)
		assert.True(t, valid)
	})
}

func TestArgon2HashMakeRandomSalt(t *testing.T) {
	hasher := Argon2()
	first, err := hasher.HashMake("password1")
	require.NoError(t, err)
	second, err := hasher.HashMake("password1")
	require.NoError(t, err)

	firstParts := strings.Split(first, "$")
	secondParts := strings.Split(second, "$")
	require.Len(t, firstParts, 6)
	require.Len(t, secondParts, 6)
	assert.NotEmpty(t, firstParts[4])
	assert.NotEmpty(t, secondParts[4])
	assert.NotEqual(t, firstParts[4], secondParts[4])
}

// Generated for "password1" with the old fixed salt and default parameters.
const legacyArgon2Hash = "$argon2id$v=19$m=65536,t=3,p=4$g3/v5Sec/J4OQnsB6fpJow$KMpCjMfljmXPrBBj/va47WFNTWoqUXHB/HDoNCoUyv0"

func TestArgon2HashCheckLegacyHash(t *testing.T) {
	valid, err := Argon2().HashCheck("password1", legacyArgon2Hash)
	require.NoError(t, err)
	assert.True(t, valid)

	valid, err = Argon2().HashCheck("wrong password", legacyArgon2Hash)
	require.NoError(t, err)
	assert.False(t, valid)
}

func TestArgon2HashCheckLegacyShortSalt(t *testing.T) {
	// Generated by the old implementation with a custom 4-byte salt.
	const hashed = "$argon2id$v=19$m=8192,t=2,p=1$g3/v5Q$EAaLjhagvDnep+XjOgceLA"

	valid, err := Argon2().HashCheck("password1", hashed)
	require.NoError(t, err)
	assert.True(t, valid)
}

func TestArgon2HashMakeRejectsInvalidConfig(t *testing.T) {
	tests := []struct {
		name   string
		change func(*Argon2Config)
	}{
		{"empty salt", func(c *Argon2Config) { c.SaltLength = 0 }},
		{"short salt", func(c *Argon2Config) { c.SaltLength = 7 }},
		{"oversized salt", func(c *Argon2Config) { c.SaltLength = 65 }},
		{"short key", func(c *Argon2Config) { c.KeyLength = 3 }},
		{"oversized key", func(c *Argon2Config) { c.KeyLength = 65 }},
		{"insufficient memory", func(c *Argon2Config) { c.Memory = 31 }},
		{"excessive memory", func(c *Argon2Config) { c.Memory = 128*1024 + 1 }},
		{"zero iterations", func(c *Argon2Config) { c.Iterations = 0 }},
		{"excessive iterations", func(c *Argon2Config) { c.Iterations = 11 }},
		{"zero parallelism", func(c *Argon2Config) { c.Parallelism = 0 }},
		{"excessive parallelism", func(c *Argon2Config) { c.Parallelism = 17 }},
		{"excessive combined cost", func(c *Argon2Config) { c.Iterations = 5 }},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			config := defaultArgon2Config
			tt.change(&config)
			hashed, err := Argon2(config).HashMake("password1")
			require.Error(t, err)
			assert.Empty(t, hashed)
		})
	}
}

func TestArgon2HashCheckRejectsInvalidHash(t *testing.T) {
	tests := []struct {
		name  string
		field int
		value string
	}{
		{"invalid prefix", 0, "extra"},
		{"wrong algorithm", 1, "argon2i"},
		{"unsupported version", 2, "v=16"},
		{"trailing version data", 2, "v=19extra"},
		{"trailing parameter data", 3, "m=65536,t=3,p=4extra"},
		{"insufficient memory", 3, "m=31,t=3,p=4"},
		{"excessive memory", 3, "m=131073,t=1,p=4"},
		{"zero iterations", 3, "m=65536,t=0,p=4"},
		{"excessive iterations", 3, "m=8192,t=11,p=4"},
		{"zero parallelism", 3, "m=65536,t=3,p=0"},
		{"excessive parallelism", 3, "m=65536,t=3,p=17"},
		{"excessive combined cost", 3, "m=65536,t=5,p=4"},
		{"empty salt", 4, ""},
		{"invalid salt encoding", 4, "!!"},
		{"newline in salt", 4, "g3/v5Sec/\nJ4OQnsB6fpJow"},
		{"oversized salt", 4, strings.Repeat("A", 87)},
		{"oversized input", 4, strings.Repeat("A", 256)},
		{"empty key", 5, ""},
		{"short key", 5, "AAAA"},
		{"oversized key", 5, strings.Repeat("A", 87)},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			parts := strings.Split(legacyArgon2Hash, "$")
			parts[tt.field] = tt.value
			valid, err := Argon2().HashCheck("password1", strings.Join(parts, "$"))
			require.Error(t, err)
			assert.False(t, valid)
		})
	}
}
